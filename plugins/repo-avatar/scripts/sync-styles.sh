#!/usr/bin/env bash
# Sync the custom styles in hooks/styles/ into the mod.
#
# A custom style is hooks/styles/<name>.ts, its name in kebab case, exporting `create` (and
# optionally `meta`); see hooks/styles/blob.ts. A mod cannot list or load files at run time, so:
#   - hooks/styles/index.ts imports each style file by name (generated here), and
#   - plugin.json's `style` picker lists the custom styles, then the bundled DiceBear ones, since
#     Claude Code treats a style outside that list as unset.
# vendor-dicebear.sh runs this too, after it regenerates the bundle.
#
# Needs node. Usage: scripts/sync-styles.sh [--check]
#   --check   change nothing; fail when index.ts or plugin.json is out of date (what CI runs)

set -euo pipefail

plugin=$(cd "$(dirname "$0")/.." && pwd)

node -e '
  const fs = require("fs")
  const path = require("path")
  const [plugin, mode = ""] = process.argv.slice(1)
  if (mode !== "" && mode !== "--check") {
    console.error("usage: scripts/sync-styles.sh [--check]")
    process.exit(2)
  }
  const isCheck = mode === "--check"
  const rel = file => path.relative(plugin, file)
  const fail = message => {
    console.error(`error: ${message}`)
    process.exit(1)
  }

  const stylesDir = path.join(plugin, "hooks/styles")
  const indexPath = path.join(stylesDir, "index.ts")
  const manifestPath = path.join(plugin, ".claude-plugin/plugin.json")
  const vendorIndex = path.join(plugin, "hooks/vendor/dicebear.js")
  const kebab = name => name.replace(/[A-Z]/g, letter => "-" + letter.toLowerCase())
  const camel = name => name.replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase())

  // The bundled styles, off the index vendor-dicebear.sh writes: `export const styles = { a, b }`.
  const line = fs.readFileSync(vendorIndex, "utf8").match(/^export const styles = \{ (.*) \}$/m)
  if (line === null) fail(`${rel(vendorIndex)} lists no styles; run scripts/vendor-dicebear.sh`)
  const bundled = line[1].split(", ").map(kebab).sort()

  const errors = []
  const custom = []
  for (const file of fs.existsSync(stylesDir) ? fs.readdirSync(stylesDir).sort() : []) {
    const full = path.join(stylesDir, file)
    if (file === "index.ts" || /\.(test|d)\.ts$/.test(file) || !fs.statSync(full).isFile()) continue
    const name = file.replace(/\.ts$/, "")
    if (!file.endsWith(".ts")) {
      errors.push(`${rel(full)}: a style is a .ts file`)
    } else if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(name)) {
      errors.push(`${rel(full)}: name a style in kebab case, like my-style.ts`)
    } else if (bundled.includes(name)) {
      errors.push(`${rel(full)}: ${name} is already a bundled DiceBear style; pick another name`)
    } else {
      custom.push(name)
    }
  }

  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"))
  const field = manifest.userConfig && manifest.userConfig.style
  if (!field) fail(`${rel(manifestPath)} has no userConfig.style`)
  field.options = [...custom, ...bundled]
  if (!field.options.includes(field.default)) {
    errors.push(`${rel(manifestPath)}: the default style ${field.default} is not one of the styles`)
  }
  if (errors.length > 0) fail(errors.join("\nerror: "))

  // Each style is imported as <camelName>Style, so a name like new.ts is no reserved word.
  const index = [
    "// Generated by scripts/sync-styles.sh from the style files in this folder; do not edit.",
    "// To add a style, write hooks/styles/<name>.ts exporting `create` (see blob.ts), then run it.",
    "",
    "import type { Style } from \"../vendor/dicebear.js\"",
    ...(custom.length > 0 ? ["", ...custom.map(name => `import * as ${camel(name)}Style from \"./${name}\"`)] : []),
    "",
    custom.length > 0
      ? ["export const customStyles: Readonly<Record<string, Style>> = {",
         ...custom.map(name => `  \"${name}\": ${camel(name)}Style,`), "}"].join("\n")
      : "export const customStyles: Readonly<Record<string, Style>> = {}",
    "",
  ].join("\n")
  const outputs = [[indexPath, index], [manifestPath, JSON.stringify(manifest, null, 2) + "\n"]]

  if (isCheck) {
    const stale = outputs.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text)
    for (const [file] of stale) {
      console.error(`error: ${rel(file)} is out of date with hooks/styles/; run scripts/sync-styles.sh`)
    }
    if (stale.length > 0) process.exit(1)
    console.log(`styles in sync: ${custom.length} custom, ${bundled.length} bundled`)
  } else {
    for (const [file, text] of outputs) fs.writeFileSync(file, text)
    console.log(`wrote ${rel(indexPath)} and the style options in ${rel(manifestPath)}: ` +
      `${custom.length} custom (${custom.join(", ") || "none"}), ${bundled.length} bundled`)
  }
' "$plugin" "${1:-}"
