#!/usr/bin/env bash
# Regenerate the vendored DiceBear bundle the mod imports.
#
# A mod runs with no Node and no `import()`, so it cannot resolve npm packages: DiceBear's core and
# every style in its collection are bundled into ES modules under hooks/vendor/, which are
# committed. The engine reads no module file over 1 MiB, so each style is a file of its own:
#
#   hooks/vendor/dicebear/core.js            createAvatar
#   hooks/vendor/dicebear/styles/<name>.js   one per style, named as @dicebear/collection exports it
#   hooks/vendor/dicebear.js                 the index the mod imports: createAvatar, styles, version
#
# It also rewrites THIRD_PARTY_LICENSES.md from the packages' own LICENSE files, then runs
# sync-styles.sh, which lists the bundled and custom (hooks/styles/) styles in the `style` picker.
#
# Needs node, npm and jq. Usage: scripts/vendor-dicebear.sh

set -euo pipefail

CORE=9.4.3
COLLECTION=9.4.3
ESBUILD=0.28.2
MAX_BYTES=1048576

plugin=$(cd "$(dirname "$0")/.." && pwd)
vendor="$plugin/hooks/vendor"
licenses="$plugin/THIRD_PARTY_LICENSES.md"
banner="// Generated by scripts/vendor-dicebear.sh from @dicebear/core@$CORE and @dicebear/collection@$COLLECTION; do not edit. Licenses: THIRD_PARTY_LICENSES.md."

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

cd "$work"
npm init -y >/dev/null
npm install --no-audit --no-fund --save-exact \
  "@dicebear/core@$CORE" "@dicebear/collection@$COLLECTION" "esbuild@$ESBUILD" >/dev/null

# One entry per style, read off the collection's own index (`import * as pixelArt from
# '@dicebear/pixel-art'`), and a list of [exportName, kebab-name] pairs for the index and picker.
mkdir -p entries/styles
echo "export { createAvatar } from '@dicebear/core'" > entries/core.mjs
node -e '
  const fs = require("fs")
  const index = fs.readFileSync("node_modules/@dicebear/collection/lib/index.js", "utf8")
  const pairs = [...index.matchAll(/import \* as (\w+) from .@dicebear\/([\w-]+)./g)].map(m => [m[1], m[2]])
  if (pairs.length === 0) throw new Error("no styles found in @dicebear/collection")
  for (const [name, pkg] of pairs) {
    // The mod finds a style by camel-casing its kebab name; check that lands on the export.
    const camel = pkg.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
    if (camel !== name) throw new Error(`style ${pkg} exports as ${name}, not ${camel}`)
    fs.writeFileSync(`entries/styles/${name}.mjs`, `export * from "@dicebear/${pkg}"\n`)
  }
  fs.writeFileSync("pairs.json", JSON.stringify(pairs))
'

rm -rf "$vendor/dicebear" "$vendor/dicebear.js"
./node_modules/.bin/esbuild entries/core.mjs entries/styles/*.mjs \
  --bundle --format=esm --platform=neutral --main-fields=module,main \
  --minify --legal-comments=none --log-level=warning \
  --banner:js="$banner" --outbase=entries --outdir="$vendor/dicebear"

node -e '
  const fs = require("fs")
  const [out, banner, version] = process.argv.slice(1)
  const pairs = JSON.parse(fs.readFileSync("pairs.json", "utf8"))
  const lines = [banner, "export { createAvatar } from \"./dicebear/core.js\""]
  for (const [name] of pairs) lines.push(`import * as ${name} from "./dicebear/styles/${name}.js"`)
  lines.push(`export const styles = { ${pairs.map(([name]) => name).join(", ")} }`)
  lines.push(`export const version = "${version}"`)
  fs.writeFileSync(out, lines.join("\n") + "\n")
' "$vendor/dicebear.js" "$banner" "$CORE/$COLLECTION"

# The engine refuses a module holding import(), the sandbox has no eval or Function, and no
# module file over 1 MiB is read.
status=0
while IFS= read -r file; do
  if grep -Eq 'import\(|\beval\(|new Function' "$file"; then
    echo "error: $file uses import(), eval or new Function, which a mod cannot load" >&2
    status=1
  fi
  if [ "$(wc -c < "$file")" -gt "$MAX_BYTES" ]; then
    echo "error: $file is over $MAX_BYTES bytes, which the engine does not read" >&2
    status=1
  fi
done < <(find "$vendor/dicebear" "$vendor/dicebear.js" -name '*.js')
[ "$status" -eq 0 ] || exit 1

{
  echo "# Third-party licenses"
  echo
  echo "\`hooks/vendor/\` bundles DiceBear (https://www.dicebear.com) core $CORE and the styles of its"
  echo "collection $COLLECTION. The code is MIT. Several styles' artwork has its own license (some"
  echo "CC BY 4.0, which asks for attribution); each package's LICENSE follows as shipped."
  for dir in node_modules/@dicebear/*/; do
    name=@dicebear/$(basename "$dir")
    version=$(jq -r .version "$dir/package.json")
    echo
    echo "## $name $version"
    echo
    if [ -f "$dir/LICENSE" ]; then
      echo '```'
      cat "$dir/LICENSE"
      echo '```'
    else
      echo "License: $(jq -r '.license // "unknown"' "$dir/package.json")"
    fi
  done
} > "$licenses"

total=$(find "$vendor/dicebear" "$vendor/dicebear.js" -name '*.js' -exec cat {} + | wc -c | tr -d ' ')
echo "wrote $vendor/dicebear.js and $vendor/dicebear/ ($total bytes, $(jq length pairs.json) styles)"
echo "wrote $licenses"
"$plugin/scripts/sync-styles.sh"
